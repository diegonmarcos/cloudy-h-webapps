#!/usr/bin/env node
// Generates the ONE shared top nav of the service fallback pages (_shared/dist/nav.js + nav.css + index.html)
// from the SuperApp app list (a_Portals/cloud-superapp/src/data/cloud-apps.json, itself generated from
// cloud-u-android aa_cloud-superapp/build.json). The service pages include /cloud-webapps/nav.js + nav.css.
// Since #1320 M7 the apps are routes of the cloudy-webapps site (the old per-app stub folders are retired); an app
// whose old slug moved links straight to its new page (scripts/lib/old-paths.mjs STUB_RENAMES).
// `--check` fails when the committed output is out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STUB_RENAMES } from './lib/old-paths.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// In the Pages repo the list sits at ../a_Portals/...; in cloud-webapps use the vendored copy (scripts/cloud-apps.json).
const pagesList = join(root, '../a_Portals/cloud-superapp/src/data/cloud-apps.json');
const list = JSON.parse(readFileSync(existsSync(pagesList) ? pagesList : join(root, 'scripts/cloud-apps.json'), 'utf8'));
// Web-only sites with no APK tile (#1063): one per backend, c3-*.
const WEB_ONLY = [['c3-mail', 'C3 Mail'], ['c3-security-network', 'C3 Security & Network'], ['c3-dns-routing', 'C3 DNS & Routing'], ['c3-observability', 'C3 Observability'], ['c3-mcp-apis', 'C3 MCP & APIs']];
const ALIAS = { 'cloud-media-center': 'cloud-media', 'cloud-terminal-nix': 'cloud-terminal' }; // extapp id -> APK/site name
const BY_ID = { 'c3-bot': 'c3-bot', 'ai-chat': 'ai-chat', 'cloud-superapp': 'cloud-superapp' };

const services = JSON.parse(readFileSync(join(root, 'scripts/fallback-services.json'), 'utf8')).services;
const apps = [], seen = new Set();
for (const g of list.groups) for (const t of g.tiles) {
  let slug = null;
  const m = /^extapp:([a-z0-9-]+)/.exec(t.target || '');
  if (m) slug = ALIAS[m[1]] ?? m[1]; else if (t.id && BY_ID[t.id]) slug = BY_ID[t.id];
  if (!slug || seen.has(slug)) continue;
  seen.add(slug); apps.push({ slug, label: t.label || slug, group: g.title });
}
for (const [slug, label] of WEB_ONLY) if (!seen.has(slug)) { seen.add(slug); apps.push({ slug, label, group: 'C3 config' }); }
const hrefOf = (slug) => STUB_RENAMES[slug] ?? `/cloud-webapps/${slug}/`;

const css = `#cwa-nav{position:sticky;top:0;z-index:99;display:flex;gap:4px;overflow-x:auto;padding:6px 10px;background:#0b0f17;border-bottom:1px solid #243049;font:13px system-ui,sans-serif;scrollbar-width:thin}
#cwa-nav a{flex:none;padding:5px 10px;border-radius:8px;color:#9aa4b2;text-decoration:none;white-space:nowrap}
#cwa-nav a:hover{color:#e6e9ef}#cwa-nav a[aria-current]{background:#4cc2ff;color:#04121c;font-weight:600}
#cwa-nav a.home{color:#4cc2ff;font-weight:700}
html[data-embed] #cwa-nav{display:none}
`;
const js = `/* GENERATED by cloud-webapps/scripts/gen-nav.mjs from the SuperApp app list - DO NOT EDIT. */
(function(){
// Embedded in the SuperApp (?embed=1 or its user-agent marker): the shell draws the tab row, so the page draws none.
if(/[?&]embed=1(&|$)/.test(location.search)||navigator.userAgent.indexOf('CloudSuperApp-Embed')>=0){document.documentElement.setAttribute('data-embed','1');return}
var B='/cloud-webapps/',A=${JSON.stringify(apps.map(a => [a.slug, a.label, hrefOf(a.slug)]))};
var cur=(location.pathname.split(B)[1]||'').split('/')[0];
var n=document.createElement('nav');n.id='cwa-nav';n.setAttribute('aria-label','Cloud apps');
n.innerHTML='<a class="home" href="'+B+'">Cloud</a>'+A.map(function(a){return '<a href="'+a[2]+'"'+(a[0]===cur?' aria-current="page"':'')+'>'+a[1]+'</a>'}).join('');
function put(){document.body.insertBefore(n,document.body.firstChild);var c=n.querySelector('[aria-current]');if(c&&c.scrollIntoView)c.scrollIntoView({inline:'center',block:'nearest'})}
if(document.body)put();else document.addEventListener('DOMContentLoaded',put);})();
`;
const index = `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Cloud web apps</title>
<link rel="stylesheet" href="/cloud-webapps/nav.css"><script src="/cloud-webapps/nav.js" defer></script>
<style>body{margin:0;background:#0b0f17;color:#e6e9ef;font:16px/1.5 system-ui,sans-serif}main{max-width:860px;margin:0 auto;padding:24px 16px}a{color:#4cc2ff}ul{columns:2;padding-left:1.2em}h2{font-size:1.1rem;margin:1.6em 0 .4em}</style></head>
<body><main><h1>Cloud web apps</h1><p>Every Cloud app, on the web.</p><ul>${apps.map(a => `<li><a href="${hrefOf(a.slug)}">${a.slug}</a> <small>${a.label}</small></li>`).join('')}</ul><h2>Services</h2><p>One page per container or service (sign-in and access help).</p><ul class="svc">${services.map(v => `<li><a href="/cloud-webapps/${v.slug}/">${v.slug}</a></li>`).join('')}</ul></main></body></html>
`;
const out = { '_shared/dist/nav.js': js, '_shared/dist/nav.css': css, '_shared/dist/index.html': index };
let bad = 0;
for (const [f, c] of Object.entries(out)) {
  const p = join(root, f);
  if (process.argv.includes('--check')) { if (!existsSync(p) || readFileSync(p, 'utf8') !== c) { console.error('stale', f); bad++; } }
  else writeFileSync(p, c);
}
if (bad) process.exit(1);
console.log(`${apps.length} apps, one shared nav`);
