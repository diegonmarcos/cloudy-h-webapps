#!/usr/bin/env node
// gen-icons.mjs — the two icon sprites of @cloudy/ui, GENERATED (#1320 C.1 `icons`):
//   sprite-sa.svg : every SuperApp drawable aa_cloud-superapp/app/src/main/res/drawable/ic_*.xml (VectorDrawable -> SVG
//                   symbol `sa-<name>`); the SuperApp sections, page tabs and Cloud tiles name these.
//   sprite-ui.svg : the fleet's nav icon catalog libs/ui-icons UiIcons.kt (declared name -> Icons.Outlined.<Glyph>), drawn
//                   from the Material Icons Outlined SVGs (the set Compose's material-icons-extended is generated from),
//                   pinned to @material-design-icons/svg@MDI; symbol `mi-<glyph>`; + the brand `assistant` mark.
//   icons.json    : { sa: [names], ui: { name: glyph }, brand: [...], fallback } — what the components resolve against.
//   node scripts/gen-icons.mjs [--android <dir>] [--check]
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { need, listDir, emit, CHECK } from './lib/android-src.mjs';
import { vectorBody, snake } from './lib/vector.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DRAWABLE = 'aa_cloud-superapp/app/src/main/res/drawable';
const UI_ICONS = 'ab_cloud-libs-shared/libs/ui-icons/src/main/kotlin/com/diegonmarcos/superapp/uiicons/UiIcons.kt';
const MDI = '0.14.15';
const HEADER = 'GENERATED by scripts/gen-icons.mjs from diegonmarcos/cloudy-u-android — DO NOT EDIT. Re-run: node scripts/gen-icons.mjs';

async function pool(items, n, fn) {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < items.length) { const k = i++; out[k] = await fn(items[k]); } }));
  return out;
}

// 1. SuperApp drawables
const names = listDir(DRAWABLE).filter((f) => /^ic_.*\.xml$/.test(f)).map((f) => f.slice(0, -4)).sort();
const sa = [];
for (const n of names) {
  const v = vectorBody(need(`${DRAWABLE}/${n}.xml`));
  if (!v) continue; // a non-vector (adaptive icon, layer-list) has no glyph to port
  sa.push([n, `<symbol id="sa-${n}" viewBox="${v.viewBox}" fill="currentColor">${v.body}</symbol>`]);
}
if (sa.length < 150) throw new Error(`only ${sa.length} SuperApp glyphs converted`);

// 2. UiIcons catalog
const kt = need(UI_ICONS);
const table = /tintedTable[\s\S]*?mapOf\(([\s\S]*?)\n\s*\)\s*\n\s*\}/.exec(kt)?.[1] ?? (() => { throw new Error('UiIcons tintedTable not found'); })();
const ui = {};
for (const m of table.matchAll(/"([^"]+)" to Icons\.Outlined\.(\w+)/g)) ui[m[1]] = snake(m[2]);
if (Object.keys(ui).length < 150) throw new Error(`UiIcons: only ${Object.keys(ui).length} names read`);
const fallbackIdent = /val FALLBACK: ImageVector get\(\) = Icons\.Outlined\.(\w+)/.exec(kt)?.[1] ?? 'Tab';
const fallback = snake(fallbackIdent);
const glyphs = [...new Set([...Object.values(ui), fallback])].sort();
async function fetchGlyph(g) {
  for (const name of [g, g.replace(/_(\d)/g, '$1')]) {
    const r = await fetch(`https://cdn.jsdelivr.net/npm/@material-design-icons/svg@${MDI}/outlined/${name}.svg`);
    if (r.ok) return await r.text();
  }
  throw new Error(`Material Icons Outlined glyph not found: ${g}`);
}
const svgs = await pool(glyphs, 8, fetchGlyph);
// The first row's own glyphs (libs:ui-nav-bars draws Icons.Filled.AutoAwesome / AccountCircle / MoreVert / ArrowDropDown).
const NAVBARS = 'ab_cloud-libs-shared/libs/ui-nav-bars/src/main/kotlin/com/diegonmarcos/superapp';
const filled = [...new Set(['navbartop1/NavBarTopFirstRow.kt', 'navbartop2/NavBarTopSecondRow.kt', 'navbarbottom/NavBarBottom.kt']
  .flatMap((f) => [...need(`${NAVBARS}/${f}`).matchAll(/Icons\.Filled\.(\w+)/g)].map((m) => snake(m[1]))))].sort();
async function fetchFilled(g) {
  const r = await fetch(`https://cdn.jsdelivr.net/npm/@material-design-icons/svg@${MDI}/filled/${g}.svg`);
  if (!r.ok) throw new Error(`Material Icons Filled glyph not found: ${g}`);
  return r.text();
}
const filledSvgs = await pool(filled, 4, fetchFilled);
const mi = glyphs.map((g, i) => {
  const s = svgs[i];
  const vb = /viewBox="([^"]+)"/.exec(s)?.[1] ?? '0 0 24 24';
  const body = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return [g, `<symbol id="mi-${g}" viewBox="${vb}" fill="currentColor">${body}</symbol>`];
});
const mf = filled.map((g, i) => {
  const s = filledSvgs[i];
  return [g, `<symbol id="mf-${g}" viewBox="${/viewBox="([^"]+)"/.exec(s)?.[1] ?? '0 0 24 24'}" fill="currentColor">${s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')}</symbol>`];
});
// brand: the assistant mark (SPARKLES path, BRAND_GRADIENT across the 24x24 viewport)
const sparkles = /SPARKLES =\s*([\s\S]*?)\n\n/.exec(kt)?.[1]?.match(/"([^"]+)"/g)?.map((s) => s.slice(1, -1)).join('') ?? '';
const grad = [...(/BRAND_GRADIENT: List<Color> = listOf\(([^)]*\)[^)]*\)[^)]*\))\)/.exec(kt)?.[1] ?? '').matchAll(/0xFF([0-9A-Fa-f]{6})/g)].map((m) => '#' + m[1].toLowerCase());
if (!sparkles || grad.length !== 3) throw new Error('UiIcons assistant mark not readable');
const brand = `<symbol id="brand-assistant" viewBox="0 0 24 24"><defs><linearGradient id="brand-assistant-g" x1="0" y1="0" x2="24" y2="24" gradientUnits="userSpaceOnUse">${grad.map((c, i) => `<stop offset="${i / (grad.length - 1)}" stop-color="${c}"/>`).join('')}</linearGradient></defs><path d="${sparkles}" fill="url(#brand-assistant-g)"/></symbol>`;

const sprite = (rows) => `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- ${HEADER} -->\n${rows.map((r) => r[1]).join('\n')}\n</svg>\n`;
const json = JSON.stringify({ _generated: HEADER, mdi: MDI, sa: sa.map((r) => r[0]), ui, filled, brand: ['assistant'], fallback }, null, 2) + '\n';
emit(root, {
  'packages/cloudy-ui/icons/sprite-sa.svg': sprite(sa),
  'packages/cloudy-ui/icons/sprite-ui.svg': sprite([...mi, ...mf, ['assistant', brand]]),
  'packages/cloudy-ui/icons/icons.json': json,
}, 'gen-icons');
console.log(CHECK ? `ok: ${sa.length} SuperApp glyphs + ${glyphs.length} Material glyphs current` : `wrote ${sa.length} SuperApp glyphs, ${Object.keys(ui).length} catalog names -> ${glyphs.length} Material glyphs`);
