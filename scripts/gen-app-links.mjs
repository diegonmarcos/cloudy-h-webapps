#!/usr/bin/env node
// gen-app-links.mjs — resolves data/app-links.json (the one app -> web service mapping, #1326) into
// packages/cloudy-ui/nav/app-links.json, the file both sites read at build time.
//
//   node scripts/gen-app-links.mjs [--services-file <fallback-services.json>] [--containers <checkout>] [--check]
//
// Container targets are DERIVED, never typed: the service's own declaration in diegonmarcos/cloudy-u-containers
// (`_shared/fallback-services.json`, itself generated there from every <service>/build.json: name, mesh name,
// public hosts) gives the PRIVATE form:
//   mesh name declared  -> https://<name>.mesh.diegonmarcos.com/<path>        (mesh first, no auth)
//   otherwise           -> https://c3-pvt.diegonmarcos.com/<name>/<path>      (c3-pvt path route, Authelia/bearer)
// Never a public host (the service's `hosts`). Sources: default `gh api` on cloudy-u-containers main (CI: GH_TOKEN),
// --containers <checkout> reads <checkout>/_shared/fallback-services.json, --services-file reads that file.
// `--check` fails (exit 1) when a mapped container disappeared or its private URL changed, i.e. the committed output differs.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'packages/cloudy-ui/nav/app-links.json');
const HEADER = 'GENERATED by scripts/gen-app-links.mjs from data/app-links.json + the cloudy-u-containers service declarations (_shared/fallback-services.json) — DO NOT EDIT. Re-run: node scripts/gen-app-links.mjs';
const PVT = 'c3-pvt.diegonmarcos.com';
const args = process.argv.slice(2);
const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? resolve(args[i + 1]) : ''; };

/** Pure: mapping + services -> resolved links. Throws on any contradiction. */
export function resolveLinks(mapping, servicesDoc) {
  const bySlug = new Map(servicesDoc.services.map((s) => [s.slug, s]));
  const seen = new Set();
  const links = mapping.links.map((m) => {
    if (seen.has(m.id)) throw new Error(`duplicate mapping entry ${m.id}`);
    seen.add(m.id);
    const base = { id: m.id, kind: m.kind, reason: m.reason };
    if (m.kind === 'phone-only') return { ...base, href: null, about: true };
    if (m.kind === 'external') {
      if (!/^https:\/\//.test(m.url)) throw new Error(`${m.id}: external url must be https`);
      return { ...base, href: m.url };
    }
    if (m.kind === 'webapp') {
      if (!/^\/[a-z0-9-]+\//.test(m.path)) throw new Error(`${m.id}: webapp path must be root-absolute`);
      return { ...base, href: m.path };
    }
    if (m.kind !== 'container') throw new Error(`${m.id}: unknown kind ${m.kind}`);
    const s = bySlug.get(m.service);
    if (!s) throw new Error(`${m.id}: container "${m.service}" is not declared in cloudy-u-containers any more`);
    const sub = m.path ? m.path.replace(/^\/?/, '') : '';
    const mesh = typeof s.mesh === 'string' && s.mesh ? s.mesh : null;
    const href = mesh ? `https://${mesh}/${sub}` : `https://${PVT}/${s.slug}/${sub}`;
    const host = new URL(href).host;
    if ((s.hosts ?? []).includes(host)) throw new Error(`${m.id}: private url ${href} is a public host`);
    return { ...base, href, service: s.slug, dir: s.dir, mesh: true, via: mesh ? 'mesh' : 'c3-pvt' };
  });
  return { _generated: HEADER, links };
}

function services() {
  const f = opt('--services-file') || (opt('--containers') && join(opt('--containers'), '_shared/fallback-services.json'));
  if (f) return JSON.parse(readFileSync(f, 'utf8'));
  const raw = execFileSync('gh', ['api', '-H', 'Accept: application/vnd.github.raw', 'repos/diegonmarcos/cloudy-u-containers/contents/_shared/fallback-services.json?ref=main'],
    { maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] }).toString('utf8');
  return JSON.parse(raw);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mapping = JSON.parse(readFileSync(join(root, 'data/app-links.json'), 'utf8'));
  let text;
  try { text = JSON.stringify(resolveLinks(mapping, services()), null, 2) + '\n'; } catch (e) { console.error('FAIL', e.message); process.exit(1); }
  if (args.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('FAIL drift: packages/cloudy-ui/nav/app-links.json is stale vs cloudy-u-containers; run node scripts/gen-app-links.mjs'); process.exit(1); }
    console.log('ok: app-links.json current');
  } else { writeFileSync(OUT, text); console.log(`wrote ${JSON.parse(text).links.length} links`); }
}
