#!/usr/bin/env node
// gen-navdata.mjs — the navigation data of both sites, GENERATED from the Android `ui` declarations (#1320 B.3/B.6/C.1).
//
//   node scripts/gen-navdata.mjs [--android <dir>] [--check]
//
// Reads (read-only): aa_cloud-superapp/build.json (ui) + every fleet app ac_<id>/build.json named by ui.external_apps.
// Writes packages/cloudy-ui/nav/:
//   nav.json     : the SuperApp shell declaration (sections, pages, tiles, stacks, menus) + every fleet app (sections/pages)
//   routes.json  : every URL path both shells prerender (relative to the site base), with what it renders
//   targets.json : Android target string -> canonical web path (section:, page:, extapp:, extapp:#page:) for /t/<target>
//   app-ids.json : the [app=appId] param matcher list
// Hand-written companion: packages/cloudy-ui/nav/nav-overlay.json (what Android cannot say: list-detail flags, portals).
// The legacy shared nav (scripts/gen-nav.mjs -> /cloud-webapps/nav.js, used by the service pages) is a separate script.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { need, readRaw, emit, CHECK } from './lib/android-src.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'packages/cloudy-ui/nav';
const HEADER = 'GENERATED by scripts/gen-navdata.mjs from the Android build.json ui declarations (diegonmarcos/cloudy-u-android) — DO NOT EDIT. Re-run: node scripts/gen-navdata.mjs';
const overlay = JSON.parse(readFileSync(join(root, OUT, 'nav-overlay.json'), 'utf8'));
const fail = (m) => { throw new Error(m); };

/** Deep copy without the `_doc*` / `_vocab*` prose keys (they are Android documentation, not navigation). */
const strip = (v) => Array.isArray(v) ? v.map(strip)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, strip(x)]))
  : v;
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o?.[k] !== undefined).map((k) => [k, strip(o[k])]));

// ── SuperApp ──────────────────────────────────────────────────────────────────────────────────────
const saBuild = JSON.parse(need('aa_cloud-superapp/build.json'));
const ui = saBuild.ui ?? fail('aa_cloud-superapp/build.json has no ui');
const SHELL_KEYS = ['default_section', 'bottom_nav', 'sections', 'main_menu', 'home_groups', 'tile_columns', 'phone_grid_columns', 'top_orbs',
  'swipe_walk', 'home_actions', 'dynamic_island_action', 'notification_center', 'floating_nav', 'app_tabs', 'search_scopes', 'retired_tile_ids'];
const superapp = pick(ui, SHELL_KEYS);
superapp.external_apps = (ui.external_apps ?? []).map((e) => pick(e, ['id', 'folder', 'hub_package', 'install_package', 'site']));
for (const s of superapp.sections) {
  if (/^(cloud|c3)-/.test(s.id)) fail(`SuperApp section id ${s.id} would collide with the app-id route matcher`);
}

// ── fleet apps (every ui.external_apps id; those with ui.sections are the mimic targets) ─────────────
const cloudSec = ui.sections.find((s) => s.id === 'cloud');
const tileOf = new Map();
for (const g of cloudSec?.tile_groups ?? []) for (const t of g.tiles ?? []) {
  const m = /^extapp:([a-z0-9-]+)/.exec(t.target ?? '');
  if (m && !tileOf.has(m[1])) tileOf.set(m[1], { label: t.label, icon: t.icon, group: g.title });
}
for (const t of cloudSec?.tiles_labs ?? []) {
  const m = /^extapp:([a-z0-9-]+)/.exec(t.target ?? '');
  if (m && !tileOf.has(m[1])) tileOf.set(m[1], { label: t.label, icon: t.icon, group: 'Labs' });
}
const portals = overlay.portals ?? {};
const apps = [];
for (const e of ui.external_apps ?? []) {
  const dir = `ac_${e.id}`;
  const raw = readRaw(`${dir}/build.json`);
  const b = raw ? JSON.parse(raw) : {};
  const aui = b.ui ?? {};
  const sections = strip(aui.sections ?? []);
  const tile = tileOf.get(e.id) ?? {};
  apps.push({
    id: e.id,
    dir: raw ? dir : null,
    package: e.install_package ?? e.hub_package ?? null,
    name: b.display_name ?? tile.label ?? e.id,
    label: tile.label ?? b.display_name ?? e.id,
    icon: tile.icon ?? null,
    group: tile.group ?? null,
    category: b.category ?? null,
    description: b.description ?? null,
    kind: sections.length ? 'app' : portals[e.id] ? 'portal' : 'card',
    default_section: aui.default_section ?? aui.bottom_nav?.[0] ?? sections[0]?.id ?? null,
    bottom_nav: aui.bottom_nav ?? sections.map((s) => s.id),
    top_bar: strip(aui.top_bar ?? null),
    sections,
  });
}
const appIds = apps.map((a) => a.id).sort();

// ── routes + targets ────────────────────────────────────────────────────────────────────────────────
const routes = [];
const targets = {};
const seen = new Set();
const route = (path, r) => { if (seen.has(path)) fail(`duplicate route ${path}`); seen.add(path); routes.push({ path, ...r }); };
const walk = (prefix, pages, ctx, depth) => {
  for (const p of pages ?? []) {
    if (!p?.id) continue;
    const path = `${prefix}${p.id}/`;
    route(path, { ...ctx, page: [...(ctx.page ?? []), p.id], depth });
    if (Array.isArray(p.pages) && p.pages.length) walk(path, p.pages, { ...ctx, page: [...(ctx.page ?? []), p.id] }, depth + 1);
  }
};
route('', { kind: 'home' });
targets['section:home'] = '';
for (const s of superapp.sections) {
  if (s.id === 'home') continue;
  route(`${s.id}/`, { kind: 'section', section: s.id });
  targets[`section:${s.id}`] = `${s.id}/`;
  walk(`${s.id}/`, s.pages, { kind: 'page', section: s.id }, 1);
  for (const p of s.pages ?? []) if (p?.id) targets[`page:${s.id}/${p.id}`] = `${s.id}/${p.id}/`;
}
for (const a of apps) {
  route(`${a.id}/`, { kind: 'app', app: a.id });
  targets[`extapp:${a.id}`] = `${a.id}/`;
  for (const s of a.sections) {
    route(`${a.id}/${s.id}/`, { kind: 'app-section', app: a.id, section: s.id });
    targets[`extapp:${a.id}#page:${s.id}/`] = `${a.id}/${s.id}/`;
    walk(`${a.id}/${s.id}/`, s.pages, { kind: 'app-page', app: a.id, section: s.id }, 1);
    for (const p of s.pages ?? []) if (p?.id) targets[`extapp:${a.id}#page:${s.id}/${p.id}`] = `${a.id}/${s.id}/${p.id}/`;
  }
  if (a.kind === 'portal') route(`${a.id}/portal/`, { kind: 'portal', app: a.id });
}

// ── collision check: a service fallback page owns /cloud-webapps/<slug>/ (Pages serves it before the site) ──
const services = JSON.parse(readFileSync(join(root, 'scripts/fallback-services.json'), 'utf8')).services.map((s) => s.slug);
const extraSvc = existsSync(join(root, 'services')) ? readdirSync(join(root, 'services')) : [];
const firstSeg = new Set([...routes.map((r) => r.path.split('/')[0]).filter(Boolean), 't', '_gallery', '_app']);
const clash = [...new Set([...services, ...extraSvc])].filter((s) => firstSeg.has(s));
if (clash.length) fail(`service slug(s) collide with a site route: ${clash.join(', ')} (rename the service page or the route)`);

const json = (o) => JSON.stringify(o, null, 2) + '\n';
emit(root, {
  [`${OUT}/nav.json`]: json({ _generated: HEADER, superapp, apps }),
  [`${OUT}/routes.json`]: json({ _generated: HEADER, count: routes.length, routes }),
  [`${OUT}/targets.json`]: json({ _generated: HEADER, count: Object.keys(targets).length, targets }),
  [`${OUT}/app-ids.json`]: json(appIds),
}, 'gen-navdata');
const declared = apps.filter((a) => a.kind === 'app');
console.log(`${CHECK ? 'ok' : 'wrote'}: ${superapp.sections.length} SuperApp sections, ${apps.length} fleet apps (${declared.length} with ui.sections), ${routes.length} routes, ${Object.keys(targets).length} targets`);
